import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:negarit_mobile/features/flow/flow_state.dart';

class FlowCopy {
  const FlowCopy(this.code);

  final String code;

  String t(String english) => _packs[code]?[english] ?? english;

  String fill(String english, Map<String, String> values) {
    var text = t(english);
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value);
    }
    return text;
  }
}

FlowCopy copyOf(WidgetRef ref) {
  final code = ref.watch(chosenLanguageProvider).value?.code ?? 'en';
  return FlowCopy(code);
}

